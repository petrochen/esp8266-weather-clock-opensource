// WMO codes used by Open-Meteo. Unknown is distinct from clear sky.
inline const uint8_t* weatherIcon(int code) {
  switch (code) {
    case 0: case 1: return weather_sun;
    case 2: return weather_partly_cloudy;
    case 3: return weather_cloud;
    case 45: case 48: return weather_fog;
    case 51: case 53: case 55: case 56: case 57:
    case 61: case 63: case 65: case 66: case 67:
    case 80: case 81: case 82: return weather_rain;
    case 71: case 73: case 75: case 77: case 85: case 86: return weather_snow;
    case 95: case 96: case 97: case 99: return weather_thunder;
    default: return weather_unknown;
  }
}
